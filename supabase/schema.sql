-- Seguridad: el público solo LEE lo activo; solo los administradores escriben (RLS).

create table if not exists public.admins (          -- quién es administrador
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);
create or replace function public.is_admin() returns boolean
language sql security definer stable set search_path = public as
$$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null, category text not null default '',
  brand text default '', model text default '', sku text default '',
  description text default '', specs jsonb default '[]'::jsonb,   -- [{"k":"Resolución","v":"4K"}]
  price numeric(10,2), old_price numeric(10,2),                  -- null = sin precio (no se inventa)
  offer text default '', featured boolean default false, active boolean default true,
  image text default '', stock integer,                          -- null = sin dato de stock
  created_at timestamptz default now(), updated_at timestamptz default now()
);
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null, category text default '', description text default '',
  icon text default '', image text default '', active boolean default true
);
create table if not exists public.company (
  id int primary key default 1 check (id = 1),
  name text, logo text, email text, phone text, whatsapp text, address text,
  description text, facebook text, instagram text, tiktok text, hours text
);
create table if not exists public.home_settings (        -- banners, marcas y categorías del inicio
  id int primary key default 1 check (id = 1),
  banners jsonb default '[]'::jsonb, brands jsonb default '[]'::jsonb, categories jsonb default '[]'::jsonb
);
insert into public.home_settings (id) values (1) on conflict do nothing;
create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade,
  kind text check (kind in ('entrada','salida','ajuste')), qty integer not null,
  note text default '', created_at timestamptz default now(), created_by uuid default auth.uid()
);
create table if not exists public.events (               -- consultas/clics (no son ventas)
  id bigint generated by default as identity primary key,
  product_id bigint, kind text check (kind in ('view','cart','whatsapp')),
  created_at timestamptz default now()
);

